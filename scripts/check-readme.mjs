#!/usr/bin/env node
/**
 * Guards the one mistake the sync cannot guard against itself: a plugin added to
 * plugins.json whose regenerated README was never committed.
 *
 * Compares the picks in plugins.json against the generated table in README.md.
 * Deliberately does NOT compare versions, stars or dates: those move on their own
 * as upstream releases, and a check that fails whenever a repository gains a star
 * is a check everyone learns to ignore.
 *
 * Usage: node scripts/check-readme.mjs   (exit 1 on mismatch)
 */
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const picks = JSON.parse(readFileSync(join(ROOT, 'plugins.json'), 'utf8')).plugins.map(entry => entry.name)
const readme = readFileSync(join(ROOT, 'README.md'), 'utf8')

const begin = '<!-- BEGIN STARTER (generated by scripts/sync.mjs) -->'
const end = '<!-- END STARTER -->'
const start = readme.indexOf(begin)
const stop = readme.indexOf(end)
if (start < 0 || stop < 0) {
  console.error('::error::README.md is missing the BEGIN/END STARTER markers')
  process.exit(1)
}

const block = readme.slice(start + begin.length, stop)
const rows = block.split('\n').filter(line => line.startsWith('| [`') || /^\| \[`/.test(line))
const listed = new Set()
for (const row of rows) {
  for (const match of row.matchAll(/\[`([^`]+)`\]/g)) listed.add(match[1])
}

const missing = picks.filter(name => !listed.has(name))
const extra = [...listed].filter(name => !picks.includes(name))
const problems = []
if (missing.length) problems.push(`in plugins.json but not in the README table: ${missing.join(', ')}`)
if (extra.length) problems.push(`in the README table but not in plugins.json: ${extra.join(', ')}`)
if (rows.length !== picks.length) problems.push(`README table has ${rows.length} rows, plugins.json has ${picks.length} picks`)

if (problems.length) {
  for (const problem of problems) console.error(`::error::${problem}`)
  console.error('Run "npm run sync" and commit the result.')
  process.exit(1)
}

console.log(`README table lists all ${picks.length} picks, in sync with plugins.json.`)
